"""Role `access`: the agent's own ocserv for VPN clients (spec 06, D-67).

The bundle carries the listener settings, the hub-issued server certificate,
the sealed server key and the users as ocpasswd hashes, so local logins keep
working while the hub is down. ocserv is a supervisor program with
`autostart=false`, like dnsmasq. A change of users only rewrites `ocpasswd`
(ocserv's plain module reads it at every login) and disconnects users that
lost access; any other change restarts ocserv.

Client traffic is classified as `clients` by `kornode.net` (source = node
client pool); the session devices `vpns*` get a strict reverse-path check.
"""

from __future__ import annotations

import subprocess
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from pathlib import Path

from kornode.bundle.models import Bundle
from kornode_agent.programs import UNSET, ControlFn, Converger, supervisorctl
from kornode_agent.store import atomic_write

DEVICE = "vpns"
PASSWD = "ocpasswd"
SERVER_KEY_POINTER = "/access/server_key"


@dataclass(frozen=True)
class AccessFiles:
    """Desired files (name -> content, mode) and the users allowed to log in."""

    files: tuple[tuple[str, str, int], ...]
    users: frozenset[str]

    def content(self, name: str) -> str | None:
        return next((text for item, text, _ in self.files if item == name), None)


def render(bundle: Bundle, secrets: dict[str, str], run: Path) -> AccessFiles | None:
    access = bundle.access
    key = secrets.get(SERVER_KEY_POINTER)
    if access is None or "access" not in bundle.node.roles or not key:
        return None
    if not access.server_cert_pem or "password" not in access.auth:
        return None
    enabled = [user for user in access.users if user.enabled and user.pw_hash]
    passwd = "".join(
        f"{user.username}:{','.join(user.groups or ()) or '*'}:{user.pw_hash}\n" for user in enabled
    )
    lines = [
        "# Generated by kornode-agent from the active bundle. Do not edit.",
        f"tcp-port = {access.port}",
        *([f"udp-port = {access.port}"] if access.udp else []),
        f"device = {DEVICE}",
        "run-as-user = nobody",
        "run-as-group = nogroup",
        "use-occtl = true",
        f"occtl-socket-file = {run / 'occtl.socket'}",
        f"socket-file = {run / 'ocserv.socket'}",
        f"server-cert = {run / 'server.crt'}",
        f"server-key = {run / 'server.key'}",
        f'auth = "plain[passwd={run / PASSWD}]"',
        "max-clients = 128",
        "max-same-clients = 2",
        "keepalive = 32400",
        "dpd = 90",
        "mobile-dpd = 1800",
        "try-mtu-discovery = true",
        "isolate-workers = true",
        "predictable-ips = true",
        "ping-leases = false",
        "cisco-client-compat = true",
        "rate-limit-ms = 200",
        "auth-timeout = 240",
        "cookie-timeout = 600",
        "ban-time = 300",
        "max-ban-score = 80",
        "ban-reset-time = 1200",
        f"ipv4-network = {bundle.node.client_pool}",
        # Every client packet enters the node; the node's `from: clients`
        # egress rules decide where it goes (fail closed by default).
        "route = default",
    ]
    if bundle.dns is not None and bundle.dns.enabled:
        lines += [f"dns = {bundle.node.service_address}", "tunnel-all-dns = true"]
    return AccessFiles(
        files=(
            ("ocserv.conf", "\n".join(lines) + "\n", 0o644),
            (PASSWD, passwd, 0o600),
            ("server.crt", access.server_cert_pem, 0o644),
            ("server.key", key if key.endswith("\n") else key + "\n", 0o600),
        ),
        users=frozenset(user.username for user in enabled),
    )


def _occtl(run: Path) -> Callable[[Sequence[str]], bool]:
    def call(args: Sequence[str]) -> bool:
        try:
            result = subprocess.run(
                ["occtl", "-s", str(run / "occtl.socket"), *args],
                capture_output=True,
                timeout=15,
                check=False,
            )
        except (OSError, subprocess.SubprocessError):
            return False
        return result.returncode == 0

    return call


class AccessServer(Converger[AccessFiles]):
    def __init__(
        self,
        root: Path,
        *,
        control: ControlFn = lambda action: supervisorctl("ocserv", action),
        occtl: Callable[[Sequence[str]], bool] | None = None,
        retry_seconds: float = 15.0,
    ) -> None:
        super().__init__(retry_seconds)
        self.run = root / "run" / "access"
        self.control = control
        self.occtl = occtl or _occtl(self.run)
        self._applied: object = UNSET

    def submit(self, bundle: Bundle | None, secrets: dict[str, str]) -> None:
        self.submit_content(render(bundle, secrets, self.run) if bundle is not None else None)

    def apply(self, bundle: Bundle | None, secrets: dict[str, str]) -> bool:
        return self.apply_content(render(bundle, secrets, self.run) if bundle is not None else None)

    def apply_content(self, desired: AccessFiles | None) -> bool:
        if desired == self._applied:
            self.error = None
            return True
        previous = self._applied if isinstance(self._applied, AccessFiles) else None
        try:
            if desired is None:
                if not self.control("stop"):
                    return self.failed("supervisorctl stop ocserv failed")
                for name in ("ocserv.conf", PASSWD, "server.crt", "server.key"):
                    (self.run / name).unlink(missing_ok=True)
            else:
                # Traversable by ocserv's unprivileged workers (they open the
                # sockets here); the secrets inside are 0600 files.
                self.run.mkdir(parents=True, exist_ok=True)
                self.run.chmod(0o755)
                for name, text, mode in desired.files:
                    atomic_write(self.run / name, text.encode(), mode=mode)
                if previous is not None and all(
                    previous.content(name) == desired.content(name)
                    for name in ("ocserv.conf", "server.crt", "server.key")
                ):
                    # ocserv reads ocpasswd at each login; sessions of users
                    # that lost access are cut explicitly. A user without a
                    # session makes occtl fail, which is not an error here.
                    for user in sorted(previous.users - desired.users):
                        self.occtl(["disconnect", "user", user])
                elif not self.control("restart"):
                    return self.failed("supervisorctl restart ocserv failed")
        except OSError as exc:
            return self.failed(f"cannot write access configuration: {exc.strerror}")
        self._applied = desired
        self.error = None
        return True
