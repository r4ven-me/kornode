"""The node resolver (spec 06/07 "DNS", D-66).

dnsmasq runs as a supervisor program with `autostart=false`; the agent writes
`run/dnsmasq.conf` from the active bundle and (re)starts or stops it. The node
answers its own `node<id>.<domain>` zone from the bundle, so names of the node
keep resolving while the hub is down; the rest of the fabric zone is
forwarded to the hub resolver over the fabric. The resolver address on `lo`
is part of the desired state of `kornode.net`, never added here.
"""

from __future__ import annotations

import logging
import subprocess
import threading
from collections.abc import Callable
from pathlib import Path

from kornode.bundle.models import Bundle
from kornode_agent.store import atomic_write

log = logging.getLogger("kornode_agent.dns")

SUPERVISORCTL = ("supervisorctl", "-c", "/etc/supervisor/conf.d/kornode-agent.conf")


def _supervisorctl(action: str) -> bool:
    try:
        result = subprocess.run(
            [*SUPERVISORCTL, action, "dnsmasq"],
            capture_output=True,
            text=True,
            timeout=30,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return False
    # `stop` of a stopped program reports "not running" with a non-zero code.
    return result.returncode == 0 or "not running" in result.stdout


def render(bundle: Bundle) -> str | None:
    """dnsmasq configuration for the bundle; None when DNS is not enabled.

    Every name, zone and address was validated by the bundle model, so the
    values cannot carry option separators or newlines.
    """
    dns = bundle.dns
    if dns is None or not dns.enabled:
        return None
    zone = f"node{bundle.node_id}.{bundle.fabric.domain}"
    lines = [
        "# Generated by kornode-agent from the active bundle. Do not edit.",
        "port=53",
        f"listen-address={bundle.node.service_address}",
        # Binds the resolver address as soon as kornode.net puts it on lo.
        "bind-dynamic",
        "no-hosts",
        "domain-needed",
        "bogus-priv",
        "no-negcache",
        "cache-size=1000",
    ]
    upstreams = dns.upstream_servers or ()
    if upstreams:
        lines.append("no-resolv")
        lines.extend(f"server={server}" for server in upstreams)
    for forward in dns.forward_zones or ():
        lines.extend(f"server=/{forward.zone}/{server}" for server in forward.servers)
    # More specific than the forwarded fabric zone: the node's own names are
    # answered locally and never leave the node.
    lines.append(f"local=/{zone}/")
    addresses: dict[str, list[str]] = {}
    for record in dns.local_records or ():
        if record.type != "CNAME":
            addresses.setdefault(record.name, []).append(record.value)
    lines.extend(f"host-record={name},{','.join(values)}" for name, values in addresses.items())
    lines.extend(
        f"cname={record.name},{record.value}"
        for record in dns.local_records or ()
        if record.type == "CNAME" and record.value in addresses
    )
    return "\n".join(lines) + "\n"


class NodeResolver:
    def __init__(
        self,
        root: Path,
        *,
        control: Callable[[str], bool] = _supervisorctl,
    ) -> None:
        self.path = root / "run" / "dnsmasq.conf"
        self.control = control
        self._lock = threading.Lock()
        # The first apply of a process always (re)starts dnsmasq: after an
        # agent or container restart the program is not running yet.
        self._started = False
        self.error: str | None = None

    def apply(self, bundle: Bundle | None) -> None:
        """Converge dnsmasq to the bundle; failures are logged and kept in
        `error`, never raised: a resolver must not roll back the data plane."""
        content = render(bundle) if bundle is not None else None
        with self._lock:
            self.error = None
            try:
                self._apply(content)
            except OSError as exc:
                self.error = f"cannot write resolver configuration: {exc.strerror}"
            if self.error:
                log.warning("node resolver: %s", self.error)

    def _apply(self, content: str | None) -> None:
        if content is None:
            if self.path.exists() or not self._started:
                self._control("stop")
                self.path.unlink(missing_ok=True)
            self._started = True
            return
        try:
            unchanged = self.path.read_text(encoding="utf-8") == content
        except FileNotFoundError:
            unchanged = False
        if unchanged and self._started:
            return
        atomic_write(self.path, content.encode())
        self._control("restart")
        self._started = True

    def _control(self, action: str) -> None:
        if not self.control(action):
            self.error = f"supervisorctl {action} dnsmasq failed"
