"""Point the host's own resolver at the built-in dnsmasq (routing.host_dns).

Domain-based egress rules do NOT need this: DomainResolverService
(services/domain_resolver.py) resolves the policy's domains into nft sets on its
own schedule, independent of which resolver the host's own lookups go through --
nftables marks traffic by destination IP. Enabling this gives the host's own
traffic the blocklist/local-records effect the admin wants, the same as VPN
clients get, and lets it resolve the interlink zone.

Under network_mode: host the container shares the host's network namespace
but not its files, so the host's resolver configuration is reached through
a bind mount:

- resolv_conf: /etc/resolv.conf -> /host/etc/resolv.conf. Rewritten in
  place (a bind-mounted file can't be replaced by rename), the original is
  kept in data_dir and restored when routing.host_dns is turned off, an
  explicit restore is requested, or the `host-dns-guard` supervisor program stops
  (container shutdown) -- the host must never be left pointing at a
  resolver that no longer runs. The guard also re-asserts the file when
  NetworkManager/DHCP rewrites it.
- resolved: /etc/systemd/resolved.conf.d -> /host/resolved.conf.d. A drop-in
  sends all host lookups to dnsmasq; systemd-resolved only reads it after
  `systemctl restart systemd-resolved` on the host, which the container
  cannot do itself. `host-dns-guard` still removes the drop-in file itself
  when routing.host_dns is turned off or the container stops -- the host
  must never be left pointing at a resolver that's about to disappear even
  if picking that up still needs a restart the container can't trigger (an
  external watcher, e.g. a systemd path unit on the host, can).
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

import dns.exception
import dns.message
import dns.query
import dns.rcode

from kornode.config.models import AppConfig
from kornode.services.files import FileManager
from kornode.services.supervisor_rpc import SupervisorRpcClient, SupervisorRpcError

HOST_RESOLV_CONF = Path("/host/etc/resolv.conf")
HOST_RESOLVED_DIR = Path("/host/resolved.conf.d")
RESOLVED_DROPIN_NAME = "kornode.conf"
BACKUP_NAME = "host-resolv.conf.orig"
MARK = "# Generated by kornode"


@dataclass(frozen=True)
class HostDnsResult:
    mode: str
    changed: bool
    detail: str

    def as_dict(self) -> dict[str, object]:
        return {"mode": self.mode, "changed": self.changed, "detail": self.detail}


class HostDnsService:
    def __init__(
        self,
        config: AppConfig,
        files: FileManager | None = None,
        *,
        resolv_conf: Path = HOST_RESOLV_CONF,
        resolved_dir: Path = HOST_RESOLVED_DIR,
        readiness_probe: Callable[[], bool] | None = None,
    ) -> None:
        self.config = config
        self.files = files or FileManager()
        self.resolv_conf = resolv_conf
        self.resolved_dir = resolved_dir
        self._readiness_probe = readiness_probe or self._probe_resolver

    @property
    def mode(self) -> str:
        return self.config.routing.host_dns

    @property
    def backup_path(self) -> Path:
        return self.config.system.data_dir / BACKUP_NAME

    @property
    def dropin_path(self) -> Path:
        return self.resolved_dir / RESOLVED_DROPIN_NAME

    def wanted(self) -> bool:
        return self.mode != "off" and self.config.dns_tunnel_active()

    def apply(self) -> HostDnsResult:
        """Bring the host resolver in line with the config (idempotent).

        Also undoes the other mode's leftovers, so switching modes or
        turning the feature off never leaves a stale redirect behind.
        """
        if self.mode == "off":
            changed = self._restore_resolv_conf() | self._remove_dropin()
            return HostDnsResult(self.mode, changed, "host DNS off; managed redirects restored")
        if not self.config.dns_tunnel_active():
            return HostDnsResult(
                self.mode,
                False,
                "host DNS deferred: dnsmasq is not configured to run; "
                "existing host DNS retained (no fallback); "
                "disable host DNS or explicitly restore to opt out",
            )
        ready, detail = self.readiness()
        if not ready:
            # A transient resolver failure is NOT permission to bypass its DNS
            # policy. Keep existing redirects/backups intact and retry later.
            return HostDnsResult(
                self.mode,
                False,
                f"host DNS deferred: {detail}; existing host DNS retained (no fallback)",
            )
        if self.mode == "resolv_conf":
            if self.config.internal_dns.port != 53 or not self.resolv_conf.exists():
                return self._point_resolv_conf()
            result = self._point_resolv_conf()
            changed = self._remove_dropin()
            return HostDnsResult(self.mode, changed or result.changed, result.detail)
        if not self.resolved_dir.is_dir():
            return self._write_dropin()
        result = self._write_dropin()
        changed = self._restore_resolv_conf()
        return HostDnsResult(self.mode, changed or result.changed, result.detail)

    def restore(self) -> HostDnsResult:
        """Undo everything (container shutdown via host-dns-guard).

        Restores resolv.conf AND removes the systemd-resolved drop-in
        unconditionally, regardless of which mode was actually active --
        the host must never be left pointing at a resolver that's about to
        stop running, in either mode. Removing the drop-in still needs
        `systemctl restart systemd-resolved` on the host to actually take
        effect (the container can't trigger that itself, see
        _write_dropin), but leaving the stale file behind is strictly
        worse than leaving nothing for an external watcher to react to.
        """
        resolv_restored = self._restore_resolv_conf()
        dropin_removed = self._remove_dropin()
        changed = resolv_restored or dropin_removed
        if not changed:
            detail = "nothing to restore"
        else:
            parts = []
            if resolv_restored:
                parts.append("resolv.conf restored")
            if dropin_removed:
                parts.append("systemd-resolved drop-in removed")
            detail = "host " + ", ".join(parts)
        return HostDnsResult(self.mode, changed, detail)

    def status(self) -> dict[str, object]:
        resolv_mounted = self.resolv_conf.exists()
        resolved_mounted = self.resolved_dir.is_dir()
        ready, detail = self.readiness() if self.wanted() else (False, "host DNS not requested")
        state = "ready" if ready else "waiting"
        if self.mode == "off":
            state = "disabled"
        elif not self.config.dns_tunnel_active():
            state, detail = (
                "not_configured",
                "host DNS requested but dnsmasq is not configured to run",
            )
        return {
            "mode": self.mode,
            "wanted": self.wanted(),
            "requested": self.mode != "off",
            "resolver_ready": ready,
            "observed_state": state,
            "readiness_detail": detail,
            "failure_policy": "retain existing host DNS; no automatic fallback",
            "nameserver": self.config.internal_dns.listen,
            "resolv_conf_mounted": resolv_mounted,
            "resolv_conf_managed": resolv_mounted and self._ours(self._read(self.resolv_conf)),
            "resolved_dir_mounted": resolved_mounted,
            "resolved_dropin_present": self.dropin_path.exists(),
        }

    def readiness(self) -> tuple[bool, str]:
        """RUNTIME: observe both project-owned dnsmasq and its local DNS listener.

        This is local readiness, not upstream reachability. An outage retains
        managed DNS even if lookups fail; only explicit off/restore opts out.
        No public lookup or fallback resolver is used for the readiness check.
        """
        try:
            ready = self._readiness_probe()
        except (OSError, SupervisorRpcError, dns.exception.DNSException, ValueError):
            return False, "resolver readiness could not be verified"
        return ready, "dnsmasq is ready" if ready else "dnsmasq process/listener is not ready"

    def _probe_resolver(self) -> bool:
        rpc = SupervisorRpcClient(self.config.generated_path("supervisor.sock"))
        if rpc.get_process_info("dnsmasq").get("statename") != "RUNNING":
            return False
        # dnsmasq answers this locally (CHAOS class); unlike a public A query,
        # the probe neither requires upstream availability nor discloses names.
        query = dns.message.make_query("version.bind.", "TXT", "CH")
        response = dns.query.udp(
            query,
            self.config.internal_dns.listen,
            port=self.config.internal_dns.port,
            timeout=1,
        )
        return query.is_response(response) and response.rcode() == dns.rcode.NOERROR

    # --- resolv.conf ------------------------------------------------------

    def _desired_resolv_conf(self) -> str:
        return (
            f"{MARK}: host lookups go through the kornode dnsmasq.\n"
            f"# The original is kept in {self.backup_path} and restored when\n"
            "# kornode stops or routing.host_dns is turned off.\n"
            f"nameserver {self.config.internal_dns.listen}\n"
        )

    def _point_resolv_conf(self) -> HostDnsResult:
        if not self.resolv_conf.exists():
            return HostDnsResult(
                self.mode,
                False,
                f"{self.resolv_conf} is not mounted; add "
                f"'/etc/resolv.conf:{self.resolv_conf}' to the container volumes",
            )
        if self.config.internal_dns.port != 53:
            return HostDnsResult(
                self.mode,
                False,
                "resolv.conf can't name a port: internal_dns.port must be 53 "
                "(or use routing.host_dns: resolved)",
            )
        current = self._read(self.resolv_conf)
        desired = self._desired_resolv_conf()
        if current == desired:
            return HostDnsResult(self.mode, False, "host resolv.conf already points at dnsmasq")
        if not self._ours(current):
            # Whatever sits there now is the host's own configuration
            # (first run, or NetworkManager/DHCP rewrote it since): that is
            # what must come back on restore.
            self.files.atomic_write_text(self.backup_path, current)
        self._write_in_place(self.resolv_conf, desired)
        return HostDnsResult(self.mode, True, "host resolv.conf now points at dnsmasq")

    def _restore_resolv_conf(self) -> bool:
        if not self.resolv_conf.exists() or not self._ours(self._read(self.resolv_conf)):
            return False
        if not self.backup_path.exists():
            return False
        self._write_in_place(self.resolv_conf, self._read(self.backup_path))
        return True

    # --- systemd-resolved -------------------------------------------------

    def _desired_dropin(self) -> str:
        listen = self.config.internal_dns.listen
        port = self.config.internal_dns.port
        server = listen if port == 53 else f"{listen}:{port}"
        return (
            f"{MARK}: send all host DNS to the kornode dnsmasq.\n"
            "# Delete this file and restart systemd-resolved to undo.\n"
            "[Resolve]\n"
            # systemd appends list options across config files; the empty
            # assignment drops servers inherited from resolved.conf so
            # dnsmasq is the only global server.
            "DNS=\n"
            f"DNS={server}\n"
            "Domains=~.\n"
        )

    def _write_dropin(self) -> HostDnsResult:
        if not self.resolved_dir.is_dir():
            return HostDnsResult(
                self.mode,
                False,
                f"{self.resolved_dir} is not mounted; add "
                f"'/etc/systemd/resolved.conf.d:{self.resolved_dir}' to the container volumes",
            )
        desired = self._desired_dropin()
        if self.dropin_path.exists() and self._read(self.dropin_path) == desired:
            return HostDnsResult(self.mode, False, "systemd-resolved drop-in already in place")
        self.files.atomic_write_text(self.dropin_path, desired)
        return HostDnsResult(
            self.mode,
            True,
            f"wrote {self.dropin_path}; run `systemctl restart systemd-resolved` "
            "on the host to apply it",
        )

    def _remove_dropin(self) -> bool:
        if not self.dropin_path.exists() or not self._ours(self._read(self.dropin_path)):
            return False
        self.dropin_path.unlink()
        return True

    # --- helpers ----------------------------------------------------------

    @staticmethod
    def _ours(content: str) -> bool:
        return MARK in content

    @staticmethod
    def _read(path: Path) -> str:
        try:
            return path.read_text(encoding="utf-8")
        except OSError:
            return ""

    @staticmethod
    def _write_in_place(path: Path, content: str) -> None:
        # Not atomic on purpose: a bind-mounted file can't be replaced by
        # rename (EBUSY), only rewritten.
        with path.open("w", encoding="utf-8") as handle:
            handle.write(content)
