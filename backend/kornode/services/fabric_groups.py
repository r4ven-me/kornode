from __future__ import annotations

import fcntl
import os
from collections.abc import Callable, Iterator, Sequence
from contextlib import contextmanager
from pathlib import Path

from kornode.config.models import AppConfig
from kornode.config.reserved import AGENT_USER_RE, AGENTS_GROUP, CLIENTS_GROUP, ENROLL_GROUP
from kornode.net.addressing import derive_addresses
from kornode.registry.db import migrate, open_registry
from kornode.registry.models import Node, NodePrefix
from kornode.registry.repository import Registry
from kornode.services.files import FileManager
from kornode.services.rendered import RenderedFile
from kornode.services.users import UserService

GENERATED_HEADER = "# Generated by kornode. Manual edits may be overwritten."


class FabricGroupsService:
    def __init__(
        self,
        config: AppConfig,
        files: FileManager | None = None,
        reload_ocserv: Callable[[], None] | None = None,
    ) -> None:
        self.config = config
        self.files = files or FileManager()
        self._reload_ocserv = reload_ocserv

    def render_files(
        self, nodes: Sequence[Node], prefixes: Sequence[NodePrefix] = ()
    ) -> list[RenderedFile]:
        rendered: list[RenderedFile] = []
        if not self._has_clients_group_policy():
            rendered.append(
                RenderedFile(
                    self.group_dir() / CLIENTS_GROUP,
                    "\n".join(
                        [
                            GENERATED_HEADER,
                            "# Group: clients — server defaults apply (D-43)",
                            "",
                        ]
                    ),
                )
            )
        hub_address = derive_addresses(
            1,
            fabric_cidr=self.config.fabric.cidr,
            client_pool=self.config.fabric.client_pool,
            source_pool=self.config.fabric.source_pool,
            domain=self.config.fabric.domain,
        ).fabric_address
        rendered.extend(
            [
                RenderedFile(
                    self.group_dir() / AGENTS_GROUP,
                    "\n".join(
                        [
                            GENERATED_HEADER,
                            f"ipv4-network = {self.config.fabric.cidr}",
                            f"route = {self.config.fabric.cidr}",
                            "",
                        ]
                    ),
                ),
                RenderedFile(
                    self.group_dir() / ENROLL_GROUP,
                    "\n".join(
                        [
                            GENERATED_HEADER,
                            f"ipv4-network = {self.config.fabric.enroll_pool}",
                            f"route = {hub_address}/32",
                            "max-same-clients = 1",
                            "",
                        ]
                    ),
                ),
            ]
        )
        active = {node.id for node in nodes if node.state == "active"}
        exported = [p for p in prefixes if p.export and p.node_id in active]
        for node in nodes:
            if node.state != "active" or node.id == 1:
                continue
            address = derive_addresses(
                node.id,
                fabric_cidr=self.config.fabric.cidr,
                client_pool=self.config.fabric.client_pool,
                source_pool=self.config.fabric.source_pool,
                domain=self.config.fabric.domain,
            ).fabric_address
            rendered.append(
                RenderedFile(
                    self.user_dir() / f"agent-{node.id}",
                    "\n".join(
                        [
                            GENERATED_HEADER,
                            f"explicit-ipv4 = {address}",
                            *(f"iroute = {p.prefix}" for p in exported if p.node_id == node.id),
                            *(f"route = {p.prefix}" for p in exported if p.node_id != node.id),
                            *(f"route = {cidr}" for cidr in self.config.exported_source_cidrs()),
                            *_transport_lines(node),
                            "",
                        ]
                    ),
                    mode=0o600,
                )
            )
        return rendered

    def stale_files(self, rendered: Sequence[RenderedFile]) -> list[Path]:
        rendered_paths = {item.path for item in rendered}
        stale: list[Path] = []
        user_dir = self.user_dir()
        if user_dir.is_dir():
            stale.extend(
                path
                for path in sorted(user_dir.iterdir())
                if path.is_file() and AGENT_USER_RE.match(path.name) and path not in rendered_paths
            )
        group_dir = self.group_dir()
        if group_dir.is_dir():
            group_names = [AGENTS_GROUP, ENROLL_GROUP]
            if (group_dir / CLIENTS_GROUP) not in rendered_paths:
                group_names.append(CLIENTS_GROUP)
            for name in group_names:
                path = group_dir / name
                if path in rendered_paths or not path.is_file():
                    continue
                if name == CLIENTS_GROUP and not _has_generated_header(path):
                    continue
                if name == CLIENTS_GROUP:
                    stale.append(path)
        return stale

    def nodes(self) -> list[Node]:
        path = self.config.system.data_dir / "registry.db"
        if not path.exists():
            return []
        conn = open_registry(path)
        try:
            migrate(conn)
            return Registry(conn).list_nodes()
        finally:
            conn.close()

    def prefixes(self) -> list[NodePrefix]:
        path = self.config.system.data_dir / "registry.db"
        if not path.exists():
            return []
        conn = open_registry(path)
        try:
            migrate(conn)
            return Registry(conn).list_prefixes()
        finally:
            conn.close()

    def sync(self, *, dry_run: bool = False) -> list[Path]:
        """Write fabric ocserv group/user files and remove stale generated files.

        ocserv reads config-per-group and config-per-user files when a session
        opens, so new and removed files need no reload. When the content of an
        existing file changes (a prefix exported or withdrawn, transport
        settings) ocserv is reloaded once, if a reload hook was supplied.
        P3-03/P3-08 call this after registry mutations.
        """
        if dry_run:
            return self._sync(dry_run=True)
        with self.locked():
            return self._sync(dry_run=False)

    @contextmanager
    def locked(self) -> Iterator[None]:
        # Serialize snapshot + render + stale-file cleanup across management,
        # enrollment, maintenance and full config saves. A stale writer must not
        # recreate an agent's per-user guard after a concurrent revocation.
        path = self.config.system.generated_dir / ".fabric-groups.lock"
        path.parent.mkdir(parents=True, exist_ok=True)
        fd = os.open(path, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
        with os.fdopen(fd, "r+b") as handle:
            fcntl.flock(handle, fcntl.LOCK_EX)
            yield

    def _sync(self, *, dry_run: bool) -> list[Path]:
        rendered = self.render_files(self.nodes(), self.prefixes())
        stale = self.stale_files(rendered)
        modified = False
        changed = [item.path for item in rendered] + stale
        if dry_run:
            UserService(self.config, files=self.files).ensure_default_group(dry_run=True)
            return changed
        UserService(self.config, files=self.files).ensure_default_group()
        self.files.ensure_dir(self.group_dir())
        self.files.ensure_dir(self.user_dir(), mode=0o700)
        for item in rendered:
            if _differs(item.path, item.content):
                modified = modified or item.path.exists()
                self.files.atomic_write_text(item.path, item.content, item.mode)
        for path in stale:
            path.unlink()
        if modified and self._reload_ocserv is not None:
            self._reload_ocserv()
        return changed

    def group_dir(self) -> Path:
        return self.config.identity.config_per_group_dir or (
            self.config.system.generated_dir / "config-per-group"
        )

    def user_dir(self) -> Path:
        return self.config.identity.config_per_user_dir or (
            self.config.system.generated_dir / "config-per-user"
        )

    def _has_clients_group_policy(self) -> bool:
        return any(group.name == CLIENTS_GROUP for group in self.config.identity.group_policies)


def _has_generated_header(path: Path) -> bool:
    try:
        first = path.read_text(encoding="utf-8").splitlines()[0]
    except (IndexError, OSError, UnicodeDecodeError):
        return False
    return first == GENERATED_HEADER


def _differs(path: Path, content: str) -> bool:
    try:
        return path.read_text(encoding="utf-8") != content
    except (OSError, UnicodeDecodeError):
        return True


def _transport_lines(node: Node) -> list[str]:
    lines: list[str] = []
    for field in ("dpd", "keepalive"):
        if field in node.transport:
            lines.append(f"{field} = {int(node.transport[field])}")
    return lines
