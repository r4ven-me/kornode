from __future__ import annotations

from pathlib import Path

from kornode.config.models import AppConfig
from kornode.config.reserved import CLIENTS_GROUP
from kornode.registry.db import migrate, open_registry
from kornode.registry.repository import Registry
from kornode.services.config import ConfigService
from kornode.services.fabric_groups import FabricGroupsService


def _config(tmp_path: Path, *, fabric: bool = True, clients_policy: bool = False) -> AppConfig:
    return AppConfig.model_validate(
        {
            "system": {
                "data_dir": tmp_path / "data",
                "generated_dir": tmp_path / "generated",
                "log_dir": tmp_path / "logs",
                "secrets_dir": tmp_path / "secrets",
            },
            "fabric": {"enabled": fabric},
            "auth": {"password": {"enabled": True}},
            "identity": {
                "config_per_group_dir": tmp_path / "generated" / "groups",
                "config_per_user_dir": tmp_path / "generated" / "users",
                "group_policies": [{"name": "clients", "routes": ["10.20.0.0/16"]}]
                if clients_policy
                else [],
            },
        }
    )


def _registry(config: AppConfig) -> Registry:
    conn = open_registry(config.system.data_dir / "registry.db")
    migrate(conn)
    return Registry(conn)


def test_render_group_and_user_files_for_active_agents(tmp_path: Path) -> None:
    config = _config(tmp_path)
    registry = _registry(config)
    registry.create_node(id=1, name="hub", state="active")
    registry.create_node(id=2, name="node2", state="pending")
    registry.create_node(id=3, name="node3", state="active")
    registry.create_node(id=4, name="node4", state="revoked")
    service = FabricGroupsService(config)

    rendered = {
        item.path.name: item.content for item in service.render_files(registry.list_nodes())
    }

    assert rendered["clients"] == (
        "# Generated by kornode. Manual edits may be overwritten.\n"
        "# Group: clients — server defaults apply (D-43)\n"
    )
    assert rendered["agents"] == (
        "# Generated by kornode. Manual edits may be overwritten.\n"
        "ipv4-network = 10.99.0.0/24\n"
        "route = 10.99.0.0/24\n"
    )
    assert rendered["enroll"] == (
        "# Generated by kornode. Manual edits may be overwritten.\n"
        "ipv4-network = 10.99.255.240/28\n"
        "route = 10.99.0.1/32\n"
        "max-same-clients = 1\n"
    )
    assert rendered["agent-3"] == (
        "# Generated by kornode. Manual edits may be overwritten.\nexplicit-ipv4 = 10.99.0.3\n"
    )
    assert "agent-1" not in rendered
    assert "agent-2" not in rendered
    assert "agent-4" not in rendered


def test_clients_group_policy_overrides_generated_clients_file(tmp_path: Path) -> None:
    config = _config(tmp_path, clients_policy=True)
    service = FabricGroupsService(config)

    names = {item.path.name for item in service.render_files([])}

    assert CLIENTS_GROUP not in names


def test_stale_files_and_sync_remove_generated_fabric_files(tmp_path: Path) -> None:
    config = _config(tmp_path, fabric=False)
    group_dir = config.identity.config_per_group_dir
    user_dir = config.identity.config_per_user_dir
    assert group_dir is not None and user_dir is not None
    group_dir.mkdir(parents=True)
    user_dir.mkdir(parents=True)
    header = "# Generated by kornode. Manual edits may be overwritten.\n"
    for name in ("clients", "agents", "enroll"):
        (group_dir / name).write_text(header, encoding="utf-8")
    (group_dir / "manual").write_text("keep\n", encoding="utf-8")
    (user_dir / "agent-2").write_text(header, encoding="utf-8")
    (user_dir / "alice").write_text(header, encoding="utf-8")

    changed = FabricGroupsService(config).sync()

    assert set(changed) == {
        group_dir / "clients",
        group_dir / "agents",
        group_dir / "enroll",
        user_dir / "agent-2",
    }
    assert not (group_dir / "clients").exists()
    assert not (group_dir / "agents").exists()
    assert not (group_dir / "enroll").exists()
    assert (group_dir / "manual").exists()
    assert (user_dir / "alice").exists()


def test_nodes_missing_registry_does_not_create_file(tmp_path: Path) -> None:
    config = _config(tmp_path)
    path = config.system.data_dir / "registry.db"

    assert FabricGroupsService(config).nodes() == []
    assert not path.exists()


def test_config_service_write_rendered_files_syncs_fabric_groups(tmp_path: Path) -> None:
    config = _config(tmp_path)
    registry = _registry(config)
    registry.create_node(id=3, name="node3", state="active")
    passwd = config.secret_path("ocpasswd")
    passwd.parent.mkdir(parents=True)
    passwd.write_text("alice:$5$hash\n", encoding="utf-8")

    written = ConfigService().write_rendered_files(config)
    group_dir = config.identity.config_per_group_dir
    user_dir = config.identity.config_per_user_dir
    assert group_dir is not None and user_dir is not None

    assert config.generated_path("ocserv.conf") in written
    assert (group_dir / "agents").exists()
    assert (group_dir / "enroll").exists()
    assert (
        (user_dir / "agent-3").read_text(encoding="utf-8").endswith("explicit-ipv4 = 10.99.0.3\n")
    )
    assert passwd.read_text(encoding="utf-8") == "alice:clients:$5$hash\n"
