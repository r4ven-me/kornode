def test_stale_files_and_sync_remove_generated_user_files_of_removed_agents(
    tmp_path: Path,
) -> None:
    config = _config(tmp_path)
    group_dir = config.identity.config_per_group_dir
    user_dir = config.identity.config_per_user_dir
    assert group_dir is not None and user_dir is not None
    group_dir.mkdir(parents=True)
    user_dir.mkdir(parents=True)
    header = "# Generated by kornode. Manual edits may be overwritten.\n"
    (group_dir / "manual").write_text("keep\n", encoding="utf-8")
    (user_dir / "agent-2").write_text(header, encoding="utf-8")
    (user_dir / "alice").write_text(header, encoding="utf-8")

    changed = InterlinkGroupsService(config).sync()

    assert user_dir / "agent-2" in changed
    assert not (user_dir / "agent-2").exists()
    # Hub-generated group files are rendered, hand-written files are left alone.
    assert (group_dir / "agents").exists() and (group_dir / "enroll").exists()
    assert (group_dir / "manual").exists()
    assert (user_dir / "alice").exists()


