from __future__ import annotations

from pathlib import Path

from kornode.config.models import AppConfig
from kornode.config.reserved import CLIENTS_GROUP
from kornode.net.model import Source
from kornode.registry.db import migrate, open_registry
from kornode.registry.repository import Registry
from kornode.services.config import ConfigService
from kornode.services.interlink_groups import InterlinkGroupsService


def _config(tmp_path: Path, *, clients_policy: bool = False) -> AppConfig:
    return AppConfig.model_validate(
        {
            "system": {
                "data_dir": tmp_path / "data",
                "generated_dir": tmp_path / "generated",
                "log_dir": tmp_path / "logs",
                "secrets_dir": tmp_path / "secrets",
            },
            "auth": {"password": {"enabled": True}},
            "identity": {
                "config_per_group_dir": tmp_path / "generated" / "groups",
                "config_per_user_dir": tmp_path / "generated" / "users",
                "group_policies": [{"name": "clients", "routes": ["10.20.0.0/16"]}]
                if clients_policy
                else [],
            },
        }
    )


def _registry(config: AppConfig) -> Registry:
    conn = open_registry(config.system.data_dir / "registry.db")
    migrate(conn)
    return Registry(conn)


def test_render_group_and_user_files_for_active_agents(tmp_path: Path) -> None:
    config = _config(tmp_path)
    registry = _registry(config)
    registry.create_node(id=1, name="hub", state="active")
    registry.create_node(id=2, name="node2", state="pending")
    registry.create_node(id=3, name="node3", state="active")
    registry.create_node(id=4, name="node4", state="revoked")
    service = InterlinkGroupsService(config)

    rendered = {
        item.path.name: item.content for item in service.render_files(registry.list_nodes())
    }

    assert rendered["clients"] == (
        "# Generated by kornode. Manual edits may be overwritten.\n"
        "# Group: clients — server defaults apply (D-43)\n"
    )
    assert rendered["agents"] == (
        "# Generated by kornode. Manual edits may be overwritten.\n"
        "ipv4-network = 10.99.0.0/24\n"
        "route = 10.99.0.0/24\n"
    )
    assert rendered["enroll"] == (
        "# Generated by kornode. Manual edits may be overwritten.\n"
        "ipv4-network = 10.99.255.240/28\n"
        "route = 10.99.0.1/32\n"
        "max-same-clients = 1\n"
    )
    assert rendered["agent-3"] == (
        "# Generated by kornode. Manual edits may be overwritten.\nexplicit-ipv4 = 10.99.0.3\n"
    )
    assert "agent-1" not in rendered
    assert "agent-2" not in rendered
    assert "agent-4" not in rendered


